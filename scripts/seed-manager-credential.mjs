#!/usr/bin/env node
/**
 * One-time bootstrap: seed the MANAGER login credential into Cloudflare D1.
 *
 * WHY THIS EXISTS
 * ---------------
 * The Worker mints a manager session by verifying the typed password against the
 * PBKDF2 hash stored in D1 `settings` under `brewmaster_manager_creds_v1`
 * (see cloudflare-worker/src/auth.ts → resolvePasswordRole). Writing that row
 * requires a manager session — and minting a manager session requires the row.
 * On a fresh/partly-provisioned D1 that is a chicken-and-egg deadlock: manager
 * login fails everywhere and manager-only settings can never sync.
 *
 * This script breaks the deadlock WITHOUT weakening the Worker (no anonymous
 * bootstrap, no baked-in default hash in the repo): the owner runs it locally
 * with a password of their choice, and it derives the exact same PBKDF2 hash the
 * browser POS produces (settingsConfig.ts → hashPassword) and emits a ready
 * `wrangler d1 execute` seed file. The password never leaves your machine and is
 * never committed.
 *
 * USAGE
 * -----
 *   # from repo root or anywhere:
 *   MANAGER_PASSWORD='your-strong-password' node scripts/seed-manager-credential.mjs
 *   # optional: MANAGER_USERNAME='manager' (default), OUT='seed-manager.sql'
 *
 * Then apply it to the REMOTE D1 (from the cloudflare-worker/ folder):
 *   cd cloudflare-worker
 *   npx wrangler d1 execute system-online-db --remote --file=../seed-manager.sql
 *
 * After it runs, log in with that manager password on the POS. Change it from
 * Settings afterwards if you like — a normal manager session can now write it.
 *
 * NOTE: this seeds the MANAGER credential. To (re)seed the cashier/admin
 * credential instead, set KEY=brewmaster_admin_creds_v2.
 */

import { webcrypto as crypto } from 'node:crypto';
import { writeFileSync } from 'node:fs';

const PBKDF2_ITERATIONS = 100000; // MUST match settingsConfig.hashPassword + auth.ts
const BRANCH_ID = 'main_branch';
const KEY = process.env.KEY || 'brewmaster_manager_creds_v1';
const USERNAME = process.env.MANAGER_USERNAME || 'manager';
const OUT = process.env.OUT || 'seed-manager.sql';
const password = process.env.MANAGER_PASSWORD || process.argv[2];

if (!password) {
  console.error('ERROR: set MANAGER_PASSWORD (env) or pass the password as the first argument.');
  console.error("Example: MANAGER_PASSWORD='s3cret' node scripts/seed-manager-credential.mjs");
  process.exit(1);
}

const enc = new TextEncoder();
const toHex = (buf) => Array.from(new Uint8Array(buf)).map((b) => b.toString(16).padStart(2, '0')).join('');

/** Byte-for-byte mirror of settingsConfig.ts → hashPassword (PBKDF2 → AES-GCM-256 raw key → hex). */
async function hashPassword(pw, saltBytes) {
  const salt = saltBytes ?? crypto.getRandomValues(new Uint8Array(16));
  const keyMaterial = await crypto.subtle.importKey('raw', enc.encode(pw), 'PBKDF2', false, ['deriveBits', 'deriveKey']);
  const derivedKey = await crypto.subtle.deriveKey(
    { name: 'PBKDF2', salt, iterations: PBKDF2_ITERATIONS, hash: 'SHA-256' },
    keyMaterial,
    { name: 'AES-GCM', length: 256 },
    true,
    ['encrypt', 'decrypt']
  );
  const raw = await crypto.subtle.exportKey('raw', derivedKey);
  return { hash: toHex(raw), salt: toHex(salt) };
}

const { hash, salt } = await hashPassword(password);

// Self-check: re-derive with the same salt and confirm the hash is reproducible
// (this is exactly what the Worker does when verifying a login).
const check = await hashPassword(password, Uint8Array.from(salt.match(/../g).map((h) => parseInt(h, 16))));
if (check.hash !== hash) {
  console.error('ERROR: hash self-check failed — aborting so a bad row is never written.');
  process.exit(1);
}

const value = JSON.stringify({ username: USERNAME, hash, salt });
const docId = `global::${KEY}`;
const nowIso = new Date().toISOString();
// value is pure JSON (double quotes + hex + a plain username) — no single quotes,
// so it is safe inside a single-quoted SQL string literal.
const sql =
  `-- Generated by scripts/seed-manager-credential.mjs on ${nowIso}\n` +
  `-- Seeds the ${KEY} login credential into D1 so the operator can sign in.\n` +
  `INSERT OR REPLACE INTO settings (id, key, value, branch_id, updated_at) VALUES (\n` +
  `  '${docId}',\n` +
  `  '${KEY}',\n` +
  `  '${value}',\n` +
  `  '${BRANCH_ID}',\n` +
  `  '${nowIso}'\n` +
  `);\n`;

writeFileSync(OUT, sql);

console.log(`✓ Wrote ${OUT}`);
console.log(`  key       : ${KEY}`);
console.log(`  username  : ${USERNAME}`);
console.log(`  salt      : ${salt}`);
console.log(`  hash      : ${hash.slice(0, 16)}… (${hash.length} hex chars)`);
console.log('');
console.log('Apply to REMOTE D1:');
console.log('  cd cloudflare-worker');
console.log(`  npx wrangler d1 execute system-online-db --remote --file=../${OUT}`);
